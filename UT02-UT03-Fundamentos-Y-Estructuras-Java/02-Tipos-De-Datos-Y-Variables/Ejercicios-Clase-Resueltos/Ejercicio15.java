// Ejercicio 15: Practicar identificadores claros y significativos

public class Ejercicio15 {
    public static void main(String[] args) {
        String nombreCompletoEmpleado = "Juan Pérez";
        final double SALARIO_BASE = 1500.00;
        int numeroHijos = 2;
        boolean estadoCivilCasado = true;

        System.out.println("Nombre completo: " + nombreCompletoEmpleado);
        System.out.println("Salario base: " + SALARIO_BASE);
        System.out.println("Número de hijos: " + numeroHijos);
        System.out.println("Estado civil (casado): " + estadoCivilCasado);
    }
}