//Ejercicio 10: Operadores de incremento y decremento
public class Ejercicio10 {
    public static void main(String[] args) {
        int x = 10;

        System.out.println("Valor inicial de x: " + x);
        System.out.println("Pre-incremento: " + (++x));
        System.out.println("Post-decremento: " + (x--));
        System.out.println("Post-incremento: " + (x++));
        System.out.println("Pre-decremento: " + (--x));
    }
}

