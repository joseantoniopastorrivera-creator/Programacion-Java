/**
 * Declara una variable llamada "saldo" y asígnale un valor
 *  inicial de 1000. Utiliza operadores de asignación para:
 *  añadir 200, restar 150, y multiplicar por 1.1
 *  (incremento del 10%). Imprime el resultado final.
 */
public class Ejercicio6 {
    public static void main(String[] args) {
        double saldo = 1000;

        saldo += 200; // Añadir 200
        saldo -= 150; // Restar 150
        saldo *= 1.1; // Incremento del 10%

        System.out.println("Saldo final: " + saldo);
    }
}

