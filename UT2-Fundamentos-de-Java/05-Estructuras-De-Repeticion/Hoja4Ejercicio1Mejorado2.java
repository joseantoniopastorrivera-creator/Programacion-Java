package Hoja4_Bucles;

//Nombre de la clase
public class Hoja4Ejercicio1Mejorado2 {

    // Método main o puerta de entrada
    public static void main(String[] args) {

        // Bucle
        for (int i = 0; i <= 100; i += 5) {
            System.out.println(i);
        }
    }
}
